do $$ declare r record; begin
  for r in select policyname, tablename from pg_policies where schemaname = 'public' and policyname like '1pc:%' loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

-- profiles: your own row; admins see everyone
create policy "1pc: read own profile" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "1pc: update own profile" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- catalog tables: signed-in members read what is published; admins manage
create policy "1pc: read lessons" on public.lessons for select to authenticated using (published or public.is_admin());
create policy "1pc: manage lessons" on public.lessons for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "1pc: read milestones" on public.milestones for select to authenticated using (true);
create policy "1pc: manage milestones" on public.milestones for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "1pc: read sessions" on public.live_sessions for select to authenticated using (true);
create policy "1pc: manage sessions" on public.live_sessions for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "1pc: read news" on public.announcements for select to authenticated using (published or public.is_admin());
create policy "1pc: manage news" on public.announcements for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- personal progress: only your own rows
create policy "1pc: own lesson progress" on public.lesson_progress for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "1pc: own milestones" on public.milestone_progress for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "1pc: own activity" on public.activity_days for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "1pc: own reminders" on public.session_reminders for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

-- support: members see and write to their own tickets; admins see all and reply as staff
create policy "1pc: read tickets" on public.tickets for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "1pc: open ticket" on public.tickets for insert to authenticated with check (user_id = auth.uid() and status = 'open');
create policy "1pc: admin updates ticket" on public.tickets for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "1pc: read messages" on public.ticket_messages for select to authenticated
  using (public.is_admin() or exists (select 1 from public.tickets t where t.id = ticket_id and t.user_id = auth.uid()));
create policy "1pc: write messages" on public.ticket_messages for insert to authenticated
  with check (author_id = auth.uid() and (
    (is_staff and public.is_admin())
    or (not is_staff and exists (select 1 from public.tickets t where t.id = ticket_id and t.user_id = auth.uid() and t.status <> 'closed'))));

grant select, insert, update, delete on public.lessons, public.milestones, public.live_sessions, public.announcements to authenticated;
grant select, insert, update, delete on public.lesson_progress, public.milestone_progress, public.activity_days, public.session_reminders to authenticated;
grant select, insert on public.tickets, public.ticket_messages to authenticated;
grant update (status) on public.tickets to authenticated;
revoke all on all tables in schema public from anon;

