-- 1 Percent Club member desk: tables, security rules and helpers for Supabase.
-- Run once in the Supabase dashboard: SQL Editor → New query → paste this whole file → Run.
-- Safe to run again: it only creates what is missing and replaces functions and policies.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- members
create table if not exists public.profiles (
  id             uuid primary key references auth.users(id) on delete cascade,
  email          text not null default '',
  full_name      text not null default '' check (char_length(full_name) <= 80),
  member_no      bigint generated by default as identity unique,
  plan           text not null default 'starter' check (plan in ('starter', 'pro', 'lifetime')),
  plan_cycle     text check (plan_cycle in ('monthly', 'yearly')),
  plan_renews_at timestamptz,
  auto_renew     boolean not null default true,
  is_admin       boolean not null default false,
  created_at     timestamptz not null default now()
);

-- Members may change only their name and auto-renew; plan and admin flags change through admin functions.
revoke update on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant update (full_name, auto_renew) on public.profiles to authenticated;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select p.is_admin from public.profiles p where p.id = auth.uid()), false);
$$;

-- every new sign-up gets a profile (name comes from the sign-up form)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, coalesce(new.email, ''), left(coalesce(new.raw_user_meta_data ->> 'full_name', ''), 80))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

-- admin: set a member's plan by hand (until payments set it automatically)
create or replace function public.admin_set_plan(member uuid, new_plan text, new_cycle text default null, renews timestamptz default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'admins only'; end if;
  if new_plan not in ('starter', 'pro', 'lifetime') then raise exception 'unknown plan %', new_plan; end if;
  update public.profiles
     set plan = new_plan,
         plan_cycle = case when new_plan = 'pro' then new_cycle end,
         plan_renews_at = case when new_plan = 'pro' then renews end
   where id = member;
end $$;
revoke execute on function public.admin_set_plan(uuid, text, text, timestamptz) from public, anon;
grant execute on function public.admin_set_plan(uuid, text, text, timestamptz) to authenticated;

-- ---------------------------------------------------------------- library
create table if not exists public.lessons (
  id            uuid primary key default gen_random_uuid(),
  kind          text not null check (kind in ('video', 'ebook')),
  title         text not null check (char_length(title) between 2 and 140),
  description   text not null default '',
  category      text not null default '',
  level         text not null default 'Beginner',
  stage         smallint check (stage between 1 and 4),
  duration_secs integer check (duration_secs >= 0),
  pages         integer check (pages >= 0),
  media_url     text,
  cover_url     text,
  required_plan text not null default 'starter' check (required_plan in ('starter', 'pro', 'lifetime')),
  published     boolean not null default false,
  sort          integer not null default 0,
  created_at    timestamptz not null default now()
);

create table if not exists public.lesson_progress (
  user_id       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  lesson_id     uuid not null references public.lessons(id) on delete cascade,
  position_secs integer not null default 0 check (position_secs >= 0),
  page          integer not null default 0 check (page >= 0),
  completed     boolean not null default false,
  saved         boolean not null default false,
  updated_at    timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

-- ---------------------------------------------------------------- path
create table if not exists public.milestones (
  id     text primary key,
  stage  smallint not null check (stage between 1 and 4),
  title  text not null,
  xp     integer not null default 150,
  sort   integer not null default 0
