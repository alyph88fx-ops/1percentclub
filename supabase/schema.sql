create table if not exists public.session_reminders (
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  session_id uuid not null references public.live_sessions(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, session_id)
);

-- ---------------------------------------------------------------- desk news
create table if not exists public.announcements (
  id         uuid primary key default gen_random_uuid(),
  tag        text not null default 'News',
  title      text not null check (char_length(title) between 2 and 140),
  body       text not null default '' check (char_length(body) <= 2000),
  published  boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- support
create table if not exists public.tickets (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  subject    text not null check (char_length(subject) between 4 and 140),
  category   text not null default 'Account' check (category in ('Account', 'Billing', 'Lessons', 'Live sessions', 'Other')),
  status     text not null default 'open' check (status in ('open', 'answered', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ticket_messages (
  id         bigint generated by default as identity primary key,
  ticket_id  bigint not null references public.tickets(id) on delete cascade,
  author_id  uuid not null default auth.uid() references auth.users(id) on delete cascade,
  is_staff   boolean not null default false,
  body       text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);

-- a new message reopens or answers the ticket
create or replace function public.touch_ticket() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.tickets set updated_at = now(), status = case when new.is_staff then 'answered' else 'open' end
   where id = new.ticket_id;
  return new;
end $$;
drop trigger if exists on_ticket_message on public.ticket_messages;
create trigger on_ticket_message after insert on public.ticket_messages for each row execute function public.touch_ticket();

-- members open a ticket and its first message in one call
create or replace function public.open_ticket(subject text, category text, body text) returns bigint
language plpgsql security invoker set search_path = public as $$
declare tid bigint;
begin
  insert into public.tickets (subject, category) values (open_ticket.subject, open_ticket.category) returning id into tid;
  insert into public.ticket_messages (ticket_id, body) values (tid, open_ticket.body);
  return tid;
end $$;
revoke execute on function public.open_ticket(text, text, text) from public, anon;
grant execute on function public.open_ticket(text, text, text) to authenticated;

