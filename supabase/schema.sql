create table if not exists public.milestone_progress (
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,
  milestone_id text not null references public.milestones(id) on delete cascade,
  done_at      timestamptz not null default now(),
  primary key (user_id, milestone_id)
);

-- one row per day a member opens the desk; the streak counts consecutive days
create table if not exists public.activity_days (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  day     date not null default (now() at time zone 'Asia/Kuala_Lumpur')::date,
  primary key (user_id, day)
);

-- ---------------------------------------------------------------- live
create table if not exists public.live_sessions (
  id            uuid primary key default gen_random_uuid(),
  title         text not null check (char_length(title) between 2 and 140),
  kind          text not null default 'Live' check (kind in ('Live', 'Class', 'Q&A')),
  host          text not null default 'The 1 Percent Club desk',
  starts_at     timestamptz not null,
  duration_mins integer not null default 60 check (duration_mins between 5 and 600),
  seats         integer check (seats >= 0),
  join_url      text,
  required_plan text not null default 'starter' check (required_plan in ('starter', 'pro', 'lifetime')),
